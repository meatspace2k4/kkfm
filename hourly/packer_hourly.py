#!/usr/bin/env python3
"""Pack the 24-hour BGM set into a blob the way radio/packer.py packs the radio.

Reads BGM_24Hour_HH_<Weather>.bwav from the Stream dir, strips the trailing
CRC32 (zeroed, same as the radio packer), concatenates into
hourly_assets_blob.bin, and writes:
  hourly/hourly_assets.h   - HourlyAsset table (offset/size/hour/weather/name)
  hourly_assets.S          - .incbin of the blob as symbol hourly_assets_blob

Run from the repo root on the build host (the Pi):
  python3 hourly/packer_hourly.py [--stream-dir DIR]
Then build with -DHOURLY_USE_BLOB and link hourly_assets.S (see hourly/build.sh pi).
"""
from __future__ import annotations

import argparse
import os
import platform
import re
import sys

PATTERN = re.compile(r"^BGM_24Hour_(?P<hour>\d{2})_(?P<weather>Sunny|Rainy|Snowy)\.bwav$")
WEATHER_IDX = {"Sunny": 0, "Rainy": 1, "Snowy": 2}
BLOB = "hourly_assets_blob.bin"
ASM = "hourly_assets.S"
HDR = os.path.join("hourly", "hourly_assets.h")


def pack(stream_dir: str, root: str) -> list[tuple[int, int, int, int, str]]:
    """Returns the table [(offset, size, hour, weather_idx, name)] and writes blob/asm/header under root."""
    entries = []
    names = sorted(f for f in os.listdir(stream_dir) if PATTERN.match(f))
    offset = 0
    with open(os.path.join(root, BLOB), "wb") as blob:
        for f in names:
            m = PATTERN.match(f)
            with open(os.path.join(stream_dir, f), "rb") as fh:
                data = fh.read()
            if len(data) < 96:
                print(f"WARNING: skipped {f}: too small ({len(data)} bytes)", file=sys.stderr)
                continue
            # Strip CRC32 (last 4 bytes) and replace with zeros, as the radio packer does.
            data = data[:-4] + b"\x00\x00\x00\x00"
            blob.write(data)
            entries.append((offset, len(data), int(m.group("hour")), WEATHER_IDX[m.group("weather")], f))
            offset += len(data)

    with open(os.path.join(root, HDR), "w") as h:
        h.write("#pragma once\n#include <cstdint>\n#include <cstddef>\n\n")
        h.write("// Generated by hourly/packer_hourly.py; do not edit.\n")
        h.write("extern const uint8_t hourly_assets_blob[];\n\n")
        h.write("struct HourlyAsset { uint32_t offset; uint32_t size; int hour; int weather; const char* name; };\n\n")
        h.write("const HourlyAsset hourly_assets[] = {\n")
        for off, size, hour, w, name in entries:
            h.write(f'    {{ {off}, {size}, {hour}, {w}, "{name}" }},\n')
        h.write("};\n")
        h.write(f"const size_t hourly_assets_count = {len(entries)};\n")

    is_macos = platform.system() == "Darwin"
    asm_lines = [
        ".global _hourly_assets_blob" if is_macos else ".global hourly_assets_blob",
        ".section __TEXT,__const" if is_macos else ".section .rodata",
        ".align 4",
        "_hourly_assets_blob:" if is_macos else "hourly_assets_blob:",
        f'.incbin "{BLOB}"',
        ".align 4",
    ]
    with open(os.path.join(root, ASM), "w") as s:
        s.write("\n".join(asm_lines) + "\n")
    return entries


def main() -> int:
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), os.pardir))
    ap = argparse.ArgumentParser()
    ap.add_argument("--stream-dir", default=os.path.join(root, "radio", "Sound", "Resource", "Stream"))
    ap.add_argument("--root", default=root, help="where the blob, .S and header are written (repo root)")
    a = ap.parse_args()
    if not os.path.isdir(a.stream_dir):
        print(f"no such dir: {a.stream_dir}", file=sys.stderr)
        return 1
    entries = pack(a.stream_dir, a.root)
    total = sum(e[1] for e in entries)
    print(f"packed {len(entries)} files, {total} bytes -> {os.path.join(a.root, BLOB)}, {os.path.join(a.root, HDR)}, {os.path.join(a.root, ASM)}")
    if len(entries) != 72:
        print(f"WARNING: expected 72 files (24 hours x 3 weathers), packed {len(entries)}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
